#!/usr/bin/env python3
"""Generate src/strings_en.h from the T(L"...") calls in src/main.cpp and translations/en.tsv.

The source language of the program is Turkish: every user-visible string in main.cpp is written as
T(L"Turkish text"). When the UI language is English, T() looks the Turkish text up in the table
generated by this script and returns the English text (falling back to the Turkish text).

translations/en.tsv has one entry per line:   <Turkish text><TAB><English text>
The text must be written exactly as it appears in the C++ source (including escapes such as \\n).

Usage:
    python tools/gen_strings.py            # regenerate src/strings_en.h
    python tools/gen_strings.py --check    # only report missing / unused translations
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAIN = os.path.join(ROOT, 'src', 'main.cpp')
TSV = os.path.join(ROOT, 'translations', 'en.tsv')
OUT = os.path.join(ROOT, 'src', 'strings_en.h')

# Button captions live in a static table in main.cpp (kButtons) and are translated at runtime too.
BUTTONS = ['Durum', 'Ayrıntılı', 'Etkinleştir', 'Yedekle', 'Geri Yükle', 'Kılavuz', 'Lisans Türleri']


def main():
    check_only = '--check' in sys.argv
    src = open(MAIN, encoding='utf-8').read()
    used = []
    for t in re.findall(r'T\(L"((?:[^"\\\n]|\\.)*)"\)', src) + BUTTONS:
        if t not in used:
            used.append(t)

    table = {}
    with open(TSV, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line:
                continue
            if line.count('\t') != 1:
                sys.exit('en.tsv line %d: expected exactly one TAB' % n)
            tr, en = line.split('\t')
            table[tr] = en

    missing = [t for t in used if t not in table]
    unused = [t for t in table if t not in used]
    print('strings in source: %d, translations: %d' % (len(used), len(table)))
    for t in missing:
        print('MISSING translation:', t)
    for t in unused:
        print('unused translation :', t)
    if missing:
        sys.exit(1)
    if check_only:
        return

    lines = [
        '// Generated by tools/gen_strings.py from translations/en.tsv - do not edit by hand.',
        '#pragma once',
        '',
        'static const LangPair kEnPairs[] = {',
    ]
    for t in used:
        lines.append('    { L"%s", L"%s" },' % (t, table[t]))
    lines.append('};')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
